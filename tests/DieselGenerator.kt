// Автоматы извлечены из реальной программной документации:
// Туккель Н.И., Шалыто А.А. "Система управления дизель-генератором (фрагмент).
// Программирование с явным выделением состояний" (СПб, 2002),
// https://is.ifmo.ru/download/short_dg.pdf
//
// Взят фрагмент схемы взаимодействия автоматов, который сами авторы выделяют
// как представительный пример (их Рис. 4): A20 (корень) вкладывает A7 и A0;
// A7 вкладывает A71, A72; A0 вкладывает A1, A3, A8; A1 вкладывает A15.
// Это даёт подлинную 4-уровневую вложенность (A20->A0->A1->A15) и случай
// нескольких автоматов, вложенных в одно состояние одновременно (A1 и A3 -
// оба в состоянии "Предпусковые операции" автомата A0).
//
// Состояния, переходы, гварды и события взяты из графов переходов и текстов
// функций документа. Шесть автоматов, упомянутых в тексте A0 (A2, A4, A9,
// A10, A11, A12), но не описанных в этом фрагменте документа (их графы не
// приведены), не реализованы - проверки их состояния (y2, y4, y9, y10, y11,
// y12) заменены на простые независимые булевы переменные среды с тем же
// именем, что сохраняет полный граф состояний A0, не изобретая поведение,
// которого нет в источнике. По той же причине в C7_1/C7_2 (A7) и в OR-цепочках
// с несколькими дизъюнктами местами оставлен только основной член.
