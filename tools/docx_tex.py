"""Keep the article text in .tex while the .docx stays the layout master.

    python docx_tex.py export base.docx article.tex   # .docx -> .tex (+ media/)
    python docx_tex.py build base.docx article.tex out.docx

`export` writes every non-empty paragraph of the document with a marker
line `% @p N` (N = paragraph number in base.docx), headings as
\\subsection*, numbered paragraphs as \\item, table cells as tabular cells,
pictures as \\includegraphics of the extracted files.

`build` compares each marked paragraph of the .tex with the same paragraph
of base.docx and proposes the difference as a tracked change; nothing else
in the document is touched, so building an unedited .tex gives back
base.docx exactly. In the .tex:
  - edit the text after a `% @p N` marker to change that paragraph;
  - remove a marker with its text to delete the paragraph;
  - start a paragraph with `% @new` (optionally `% @new like=N`) to insert
    it after the previous paragraph;
  - point the \\includegraphics after `% @img N` to another file to
    replace that picture (the old one is shown deleted, the new inserted);
  - `% @comment: text` (or `% @comment resolved: text`) attaches a comment
    to the paragraph above it;
  - any other `%` line is a note for the authors and is ignored.
Inline markup: $A_{0}$ stands for "A0"; \\& \\% \\# \\_ \\{ \\} \\$ are escapes.
"""

import os
import re
import sys

from lxml import etree

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from docx_review import Doc, q  # noqa: E402

ESC = [("\\", "\\textbackslash{}"), ("&", "\\&"), ("%", "\\%"), ("#", "\\#"), ("_", "\\_"),
       ("{", "\\{"), ("}", "\\}"), ("$", "\\$")]


def to_tex(text):
    out = []
    for ch in text:
        for a, b in ESC:
            if ch == a:
                out.append(b)
                break
        else:
            out.append(ch)
    s = "".join(out)
    return re.sub(r"(?<![\w$])A(\d)(?![\w])", r"$A_{\1}$", s)


def from_tex(s):
    s = re.sub(r"\$A_\{(\d)\}\$", r"A\1", s)
    s = s.replace("\\textbackslash{}", "\0")
    for a, b in ESC[1:]:
        s = s.replace(b, a)
    return s.replace("\0", "\\")


def _bold(run):
    rpr = run.find(q("w:rPr"))
    if rpr is None:
        return False
    b = rpr.find(q("w:b"))
    return b is not None and b.get(q("w:val")) not in ("0", "false")


def export(docx_path, tex_path):
    d = Doc(docx_path)
    index = {id(p): i for i, p in enumerate(d._paras)}
    tex_dir = os.path.dirname(os.path.abspath(tex_path))
    media_dir = os.path.join(tex_dir, "media")
    os.makedirs(media_dir, exist_ok=True)
    rels = etree.parse(os.path.join(d.dir, "word", "_rels", "document.xml.rels")).getroot()
    targets = {r.get("Id"): r.get("Target") for r in rels}

    lines = [
        "%% Generated by tools/docx_tex.py from %s. The .docx is the layout master;" % os.path.basename(docx_path),
        "% this file holds the text. Build the .docx with: docx_tex.py build <base.docx> <this.tex> <out.docx>",
        "\\documentclass[12pt]{article}",
        "\\usepackage{fontspec}\\setmainfont{Liberation Serif}",
        "\\usepackage[russian]{babel}\\usepackage[margin=2.5cm]{geometry}\\usepackage{graphicx}",
        "\\begin{document}",
        "",
    ]
    in_list = False

    def close_list():
        nonlocal in_list
        if in_list:
            lines.append("\\end{enumerate}")
            lines.append("")
            in_list = False

    def para_lines(p, i):
        text = d._orig_text[i]
        if p.find(".//" + q("w:drawing")) is not None:
            out = []
            for blip in p.iter("{http://schemas.openxmlformats.org/drawingml/2006/main}blip"):
                target = targets.get(blip.get("{http://schemas.openxmlformats.org/officeDocument/2006/relationships}embed"))
                if target:
                    name = os.path.basename(target)
                    with open(os.path.join(d.dir, "word", target), "rb") as src, \
                            open(os.path.join(media_dir, name), "wb") as dst:
                        dst.write(src.read())
                    out += ["% @img " + str(i), "\\begin{center}\\includegraphics[width=0.8\\linewidth]{media/%s}\\end{center}" % name]
            return out, False
        if not text.strip():
            return [], False
        numbered = p.find(q("w:pPr") + "/" + q("w:numPr")) is not None
        runs = [r for r in p.iter(q("w:r")) if r.find(q("w:t")) is not None]
        heading = runs and all(_bold(r) for r in runs) and len(text) < 160
        body = to_tex(text)
        if numbered:
            return ["% @p " + str(i), "\\item " + body], True
        if heading:
            return ["% @p " + str(i), "\\subsection*{%s}" % body, ""], False
        return ["% @p " + str(i), body, ""], False

    for el in d.body:
        if el.tag == q("w:tbl"):
            close_list()
            rows = el.findall(q("w:tr"))
            ncols = max(len(r.findall(q("w:tc"))) for r in rows)
            lines.append("\\begin{tabular}{%s}" % ("|p{%.2f\\linewidth}" % (0.9 / ncols) * ncols + "|"))
            for r in rows:
                cells = r.findall(q("w:tc"))
                for k, c in enumerate(cells):
                    sep = " \\\\ \\hline" if k == len(cells) - 1 else " &"
                    ps = [p for p in c.findall(q("w:p")) if d._orig_text[index[id(p)]].strip()]
                    if not ps:
                        lines.append("% (empty cell)" + sep)
                    for n, p in enumerate(ps):
                        i = index[id(p)]
                        lines.append("% @p " + str(i))
                        lines.append(to_tex(d._orig_text[i]) + (sep if n == len(ps) - 1 else ""))
            lines.append("\\end{tabular}")
            lines.append("")
            continue
        if el.tag != q("w:p"):
            continue
        out, item = para_lines(el, index[id(el)])
        if not out:
            continue
        if item and not in_list:
            lines.append("\\begin{enumerate}")
            in_list = True
        if not item:
            close_list()
        lines += out
    close_list()
    lines.append("\\end{document}")
    with open(tex_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def _strip(line):
    s = line.strip()
    if s.startswith("\\item "):
        s = s[len("\\item "):]
    m = re.match(r"\\subsection\*\{(.*)\}$", s)
    if m:
        s = m.group(1)
    s = re.sub(r"\s*(&|\\\\ \\hline)$", "", s)
    return s


def parse(tex_path):
    """Return blocks: dicts with kind ('p' or 'new'), idx, like, text, comments."""
    blocks, cur = [], None
    with open(tex_path, encoding="utf-8") as f:
        for raw in f:
            line = raw.rstrip("\n")
            s = line.strip()
            m = re.match(r"%\s*@p\s+(\d+)\s*$", s)
            if m:
                cur = {"kind": "p", "idx": int(m.group(1)), "text": [], "comments": []}
                blocks.append(cur)
                continue
            m = re.match(r"%\s*@new(?:\s+like=(\d+))?\s*$", s)
            if m:
                cur = {"kind": "new", "like": int(m.group(1)) if m.group(1) else None, "text": [], "comments": []}
                blocks.append(cur)
                continue
            m = re.match(r"%\s*@img\s+(\d+)\s*$", s)
            if m:
                cur = {"kind": "img", "idx": int(m.group(1)), "text": [], "comments": [], "src": None}
                blocks.append(cur)
                continue
            m = re.search(r"\\includegraphics(?:\[[^]]*\])?\{([^}]*)\}", s)
            if m and cur is not None and cur["kind"] == "img":
                cur["src"] = m.group(1)
                cur = None
                continue
            m = re.match(r"%\s*@comment(\s+resolved)?\s*:\s*(.*)$", s)
            if m and cur is not None:
                cur["comments"].append((m.group(2), bool(m.group(1))))
                continue
            if not s:
                if cur is not None and cur["text"]:
                    cur = None
                continue
            if s.startswith("%"):
                continue
            if s.startswith("\\begin") or s.startswith("\\end") or s.startswith("\\document") \
                    or s.startswith("\\use"):
                cur = None
                continue
            if cur is not None:
                cur["text"].append(_strip(s))
    for b in blocks:
        b["text"] = from_tex(" ".join(t for t in b["text"] if t))
    return blocks


def build(base_docx, tex_path, out_docx, author="Claude"):
    d = Doc(base_docx, author=author)
    blocks = parse(tex_path)
    seen = set()
    anchor = None
    elements = {i: p for i, p in enumerate(d._paras)}
    base_text = list(d._orig_text)
    tex_dir = os.path.dirname(os.path.abspath(tex_path))
    rels = etree.parse(os.path.join(d.dir, "word", "_rels", "document.xml.rels")).getroot()
    targets = {r.get("Id"): r.get("Target") for r in rels}
    images = []
    for b in blocks:
        if b["kind"] == "img":
            if b["src"]:
                p = elements[b["idx"]]
                blip = next(p.iter("{http://schemas.openxmlformats.org/drawingml/2006/main}blip"))
                old = os.path.join(d.dir, "word", targets[blip.get(
                    "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}embed")])
                new = os.path.join(tex_dir, b["src"])
                with open(old, "rb") as f1, open(new, "rb") as f2:
                    if f1.read() != f2.read():
                        images.append((p, new))
            continue
        if b["kind"] == "p":
            p = elements[b["idx"]]
            seen.add(b["idx"])
            if b["text"] != base_text[b["idx"]]:
                d.rewrite(p, b["text"])
            anchor = p
        else:
            if anchor is None:
                raise ValueError("@new paragraph before any marked paragraph")
            like = elements[b["like"]] if b["like"] is not None else anchor
            p = d.insert_after(anchor, b["text"], like=like)
            anchor = p
        for text, resolved in b["comments"]:
            d.comment(anchor, text, resolved=resolved)
    for i, p in elements.items():
        text = base_text[i]
        if i not in seen and text.strip() and p.find(".//" + q("w:drawing")) is None:
            d.delete_paragraph(p)
    for p, new in images:
        d.replace_image(p, new)
    d.save(out_docx)


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "export":
        export(sys.argv[2], sys.argv[3])
    elif cmd == "build":
        build(sys.argv[2], sys.argv[3], sys.argv[4])
    else:
        print(__doc__)
