def block_re(kind, n):
    # marker, content line, then any @-lines already attached
    return re.compile(r"%% @%s %d\n[^\n]*\n(?:%% @(?:comment|format)[^\n]*\n)*" % (kind, n))


def find(kind, n):
    m = block_re(kind, n).search(src)
    if not m:
        raise KeyError((kind, n))
    return m


def prefix(line):
    if line.startswith("\\item "):
        return "\\item ", ""
    if line.startswith("\\subsection*{"):
        return "\\subsection*{", "}"
    return "", ""


def set_text(n, text, comment=None, resolved=False):
    global src
    m = find("p", n)
    lines = m.group(0).split("\n")
    a, b = prefix(lines[1])
    lines[1] = a + to_tex(text) + b
    if comment:
        lines.insert(-1, "%% @comment%s: %s" % (" resolved" if resolved else "", comment))
    src = src[:m.start()] + "\n".join(lines) + src[m.end():]


def comment(n, text):
    set_text(n, T[n], text)


def fmt(n, **kw):
    global src
    m = find("p", n)
    g = m.group(0)
    src = src[:m.end()] + "% @format: " + " ".join("%s=%s" % kv for kv in kw.items()) + "\n" + src[m.end():]


def delete(n):
    global src
    m = find("p", n)
    src = src[:m.start()] + src[m.end():]


def after(kind, n, paras):
    """paras: list of (text, like, comment, fmt dict)."""
    global src
    m = find(kind, n)
    add = ""
    for text, like, com, f in paras:
        add += "%% @new like=%d\n%s\n" % (like, to_tex(text))
        if f:
            add += "% @format: " + " ".join("%s=%s" % kv for kv in f.items()) + "\n"
        if com:
            add += "%% @comment: %s\n" % com
    src = src[:m.end()] + add + src[m.end():]


def image(n, png, width_cm):
    global src
    m = find("img", n)
    line = "\\begin{center}\\includegraphics[width=%.2fcm]{media/%s}\\end{center}" % (width_cm, png)
    src = src[:m.start()] + "%% @img %d\n%s\n" % (n, line) + src[m.end():]


