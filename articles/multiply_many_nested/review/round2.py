class TexEditor:
    """Writes new paragraph texts, notes and comments into the exported .tex."""

    def __init__(self, base_docx, tex_path):
        export(base_docx, tex_path)
        self.path = tex_path
        self.lines = open(tex_path, encoding="utf-8").read().split("\n")
        self.base = Doc(base_docx)
        self.notes = []

    def _marker_line(self, snippet):
        idx = self.base._paras.index(self.base.para(snippet))
        return self.lines.index("%% @p %d" % idx)

    def note(self, text):
        self.notes.append(text)

    def rewrite(self, snippet, new_text):
        k = self._marker_line(snippet)
        j = k + 1
        while self.lines[j].startswith("%"):
            j += 1
        prefix = "\\item " if self.lines[j].startswith("\\item ") else ""
        self.lines[j] = prefix + to_tex(new_text)
        self.lines[k + 1:k + 1] = ["% " + n for n in self.notes]
        self.notes = []

    def comment(self, snippet, text, resolved=False):
        k = self._marker_line(snippet)
        j = k + 1
        while self.lines[j].startswith("%"):
            j += 1
        self.lines.insert(j + 1, "%% @comment%s: %s" % (" resolved" if resolved else "", text))

    def save(self):
        with open(self.path, "w", encoding="utf-8") as f:
            f.write("\n".join(self.lines))

